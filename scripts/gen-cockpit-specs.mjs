#!/usr/bin/env node
// gen-cockpit-specs.mjs — emit specs/cockpit/0N-*.md from specs/cockpit/phases.json + templates/spec.md.
// Deterministic: run it twice, `git diff` is empty; edit one task in phases.json, only that spec changes.
// Writes a file only when its content differs (keeps git history honest). Node stdlib only.
//   node scripts/gen-cockpit-specs.mjs [--check]      --check: exit 1 if any spec would change
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const src = JSON.parse(readFileSync(join(root, 'specs/cockpit/phases.json'), 'utf8'));
const tpl = readFileSync(join(root, 'templates/spec.md'), 'utf8');
const check = process.argv.includes('--check');

const yamlList = (arr, ind = '  ') => arr.map(x => `${ind}- ${x}`).join('\n');
const yamlObj = (o, ind = '  ') => Object.entries(o).map(([k, v]) => `${ind}${k}: ${v}`).join('\n');

function render(ph) {
  const c = src.common;
  const fm = [
    '---',
    `branch: feat/${ph.slug}`,
    `release: ${ph.release}`,
    'repos:',
    ...c.repos.map(r => `  - path: ${r.path}\n    stack: ${r.stack}`),
    `phase: ${ph.phase}`,
    `depends_on: ${ph.depends_on ?? 'null'}`,
    `outward: ${c.outward}`,
    `dev_server: ${c.dev_server}`,
    'gates:',
    yamlObj(ph.gates),
    'budgets:',
    yamlObj(c.budgets),
    'manual_gates:' + (ph.manual_gates.length ? '' : ' []'),
    ...ph.manual_gates.map(g => `  - name: ${g.name}\n    what: ${g.what}\n    owner: ${c.owner}\n    due: ${g.due}`),
    '---',
  ].join('\n');

  const tasks = ph.tasks.map((t, i) =>
    `${i + 1}. ${t.t}\n   Evidence: ${t.e}\n   Verify: ${t.v}\n   Owner: ${t.o}`).join('\n\n');

  return tpl
    .replace('%%FRONT_MATTER%%', fm)
    .replace('%%TITLE%%', ph.title)
    .replace('%%GOAL%%', ph.goal)
    .replace('%%CONSTRAINTS%%', ph.constraints.map(k => `- ${k} — see ARCHITECTURE.md §14 / ledger.md`).join('\n'))
    .replace('%%TASKS%%', tasks)
    .replace('%%OUT_OF_SCOPE%%', ph.out_of_scope)
    .replace('%%GENERATED%%', `Generated by scripts/gen-cockpit-specs.mjs from specs/cockpit/phases.json — do not edit by hand.`);
}

let changed = 0;
for (const ph of src.phases) {
  const out = join(root, 'specs/cockpit', ph.file);
  const next = render(ph);
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : null;
  if (cur === next) continue;
  changed++;
  if (check) { console.error(`would change: specs/cockpit/${ph.file}`); continue; }
  writeFileSync(out, next);
  console.log(`wrote specs/cockpit/${ph.file} (${ph.tasks.length} tasks)`);
}
if (check && changed) process.exit(1);
if (!changed) console.log('specs up to date');
